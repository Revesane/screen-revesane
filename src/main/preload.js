"use strict";

const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("api", {
  listSources: () => ipcRenderer.invoke("sources:list"),
  arm: (target) => ipcRenderer.invoke("capture:arm", target),
  armLoopback: (payload) => ipcRenderer.invoke("capture:loopbackArm", payload),
  startCapture: (payload) => ipcRenderer.invoke("capture:start", payload),
  sendChunk: (buffer) => ipcRenderer.send("capture:chunk", buffer),
  finishCapture: (payload) => ipcRenderer.invoke("capture:finish", payload ?? {}),
  abortCapture: () => ipcRenderer.invoke("capture:abort"),
  screenshot: (dataUrl) => ipcRenderer.invoke("capture:screenshot", dataUrl),
  pickRegion: (payload) => ipcRenderer.invoke("region:pick", payload),
  confirmRegion: () => ipcRenderer.send("region:confirm"),
  showFrame: (payload) => ipcRenderer.invoke("frame:show", payload),
  hideFrame: () => ipcRenderer.invoke("frame:hide"),
  prewarmCapture: (payload) => ipcRenderer.invoke("capture:prewarm", payload),
  onRegionDisplay: (handler) => ipcRenderer.on("region:display", (_e, info) => handler(info)),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (patch) => ipcRenderer.invoke("settings:set", patch),
  onLang: (handler) => ipcRenderer.on("lang:changed", (_e, lang) => handler(lang)),
  diskFree: () => ipcRenderer.invoke("disk:free"),
  onRegionSnapped: (handler) => ipcRenderer.on("region:snapped", (_e, result) => handler(result)),
  checkUpdate: () => ipcRenderer.invoke("update:check"),
  updateState: () => ipcRenderer.invoke("update:state"),
  downloadUpdate: () => ipcRenderer.invoke("update:download"),
  installUpdate: () => ipcRenderer.invoke("update:install"),
  openUpdatePage: () => ipcRenderer.invoke("update:openPage"),
  onUpdateAvailable: (handler) => ipcRenderer.on("update:available", (_e, info) => handler(info)),
  onUpdateProgress: (handler) => ipcRenderer.on("update:progress", (_e, progress) => handler(progress)),
  checkHotkey: (payload) => ipcRenderer.invoke("hotkeys:check", payload),
  library: () => ipcRenderer.invoke("library:list"),
  clearLibrary: () => ipcRenderer.invoke("library:clear"),
  trimMedia: (payload) => ipcRenderer.invoke("library:trim", payload),
  videoSnapshot: (payload) => ipcRenderer.invoke("library:snapshot", payload),
  deleteMedia: (payload) => ipcRenderer.invoke("library:delete", payload),
  previewVideo: (payload) => ipcRenderer.invoke("library:preview", payload),
  probeMedia: (payload) => ipcRenderer.invoke("library:probe", payload),
  mergeMedia: (payload) => ipcRenderer.invoke("library:merge", payload),
  speedMedia: (payload) => ipcRenderer.invoke("library:speed", payload),
  readImage: (payload) => ipcRenderer.invoke("library:readImage", payload),
  saveAnnotated: (payload) => ipcRenderer.invoke("library:saveAnnotated", payload),
  copyImage: (dataUrl) => ipcRenderer.invoke("clipboard:writeImage", { dataUrl }),
  selfProtect: (enabled) => ipcRenderer.invoke("self:protect", enabled),
  reveal: (target) => ipcRenderer.invoke("shell:reveal", target),
  open: (target) => ipcRenderer.invoke("shell:open", target),
  openOutputDir: () => ipcRenderer.invoke("shell:openOutputDir"),
  info: () => ipcRenderer.invoke("app:info"),
  log: (level, message, module = "ui") => ipcRenderer.invoke("app:log", { level, message, module }),
  openLogDir: () => ipcRenderer.invoke("log:openDir"),
  logTail: (lines = 80) => ipcRenderer.invoke("log:tail", { lines }),
  minimize: () => ipcRenderer.send("win:minimize"),
  setCompact: (on) => ipcRenderer.invoke("win:compact", Boolean(on)),
  maximize: () => ipcRenderer.send("win:maximize"),
  restore: () => ipcRenderer.send("win:restore"),
  focusWindow: () => ipcRenderer.invoke("win:focus"),
  setContentProtection: (enabled) => ipcRenderer.invoke("win:contentProtection", enabled),
  close: () => ipcRenderer.send("win:close"),
  onHotkey: (handler) => {
    for (const kind of ["toggle", "stop", "pause", "screenshot", "region", "regionShot", "library", "mic", "panel"]) {
      ipcRenderer.on(`hotkey:${kind}`, () => handler(kind));
    }
  },
  onRecordCommand: (handler) => ipcRenderer.on("record:command", (_e, command) => handler(command)),
  onPreviewProgress: (handler) => ipcRenderer.on("preview:progress", (_e, payload) => handler(payload)),
  onCursor: (handler) => ipcRenderer.on("cursor:point", (_e, point) => handler(point)),
  onFfmpegState: (handler) => ipcRenderer.on("ffmpeg:state", (_e, state) => handler(state)),
  chooseDir: (current) => ipcRenderer.invoke("dialog:chooseDir", current),
  chooseImage: (current) => ipcRenderer.invoke("dialog:chooseImage", current),
  chooseThemeImage: () => ipcRenderer.invoke("theme:chooseImage"),
  panelState: (state) => ipcRenderer.send("panel:state", state),
  onSelftest: (handler) => ipcRenderer.on("selftest:run", () => handler()),
  onSelftestView: (handler) => ipcRenderer.on("selftest:view", (_e, view) => handler(view)),
  onModeTest: (handler) => ipcRenderer.on("selftest:modes", () => handler()),
  selftestReport: (payload) => ipcRenderer.invoke("selftest:report", payload),
});
